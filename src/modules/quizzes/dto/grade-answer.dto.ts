import { IsIn } from 'class-validator';

/**
 * Ручная проверка развёрнутого ответа (phase-45).
 *
 * Автопроверка засчитывает только точное совпадение с эталоном; всё остальное
 * ждёт преподавателя, и решение у него бинарное — засчитать или нет. Частичный
 * балл намеренно не поддерживаем: в текущей модели у вопроса один вес.
 */
export class GradeAnswerDto {
    @IsIn(['correct', 'incorrect'])
    verdict!: 'correct' | 'incorrect';
}
