/**
 * Порядок вопросов при импорте из Excel.
 *
 * Отдельный файл без зависимостей: сам сервис импорта тянет за собой санитайзер
 * HTML, а тот — jsdom, который под jest не поднимается. Логика здесь чистая и
 * должна быть покрыта тестом, поэтому она живёт вне сервиса.
 */

/**
 * Выстраивает разобранные строки по «№», проставленному оператором.
 *
 * Шаблон устроен «один тип вопроса — один лист», и парсер обходит листы в
 * фиксированном порядке. Без этой сортировки тест, задуманный как «одиночный,
 * соотношение, одиночный, множественный», ложится в базу сгруппированным по
 * типам, и замысел методиста теряется — это и есть жалоба «вопросы не
 * сохраняют последовательность».
 *
 * Сортируем, а не используем «№» напрямую как `order`: повторный импорт в тот
 * же тест дописывает вопросы в конец, и чужие номера там столкнулись бы с
 * позициями уже существующих.
 *
 * Строки без «№» сохраняют взаимный порядок и уходят в конец — наполовину
 * заполненная колонка деградирует предсказуемо, а не перемешивает файл.
 * Держится на том, что `Array.prototype.sort` стабильна по спецификации.
 */
export function sortByOperatorSeq<T extends { seq: number | null }>(parsed: T[]): T[] {
    if (!parsed.some((p) => p.seq != null)) return parsed;
    return [...parsed].sort((a, b) => {
        if (a.seq == null && b.seq == null) return 0;
        if (a.seq == null) return 1;
        if (b.seq == null) return -1;
        return a.seq - b.seq;
    });
}
