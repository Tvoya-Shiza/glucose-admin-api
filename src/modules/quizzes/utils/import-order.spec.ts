import { sortByOperatorSeq } from './import-order';

/**
 * Порядок вопросов при импорте из Excel.
 *
 * Шаблон устроен «один тип вопроса — один лист», и парсер обходит листы по
 * фиксированному порядку. Без сортировки по «№» замысел методиста теряется:
 * в базу попадают сначала все одиночные, потом все множественные.
 */

/** Компактная запись строки: только то, что влияет на сортировку. */
const row = (sheet: string, seq: number | null, id: string) => ({ sheet, seq, id });
const ids = (rows: Array<{ id: string }>) => rows.map((r) => r.id).join(',');

describe('sortByOperatorSeq', () => {
    it('выстраивает вопросы по «№» сквозь листы, а не группами по типу', () => {
        // Методист задумал: одиночный, соотношение, одиночный, множественный.
        // Парсер отдаёт это сгруппированным по листам.
        const parsed = [
            row('Один ответ', 1, 'a'),
            row('Один ответ', 3, 'c'),
            row('Множественный', 4, 'd'),
            row('Соотношение', 2, 'b'),
        ];
        expect(ids(sortByOperatorSeq(parsed))).toBe('a,b,c,d');
    });

    it('оставляет порядок листов, когда «№» не заполнена нигде', () => {
        const parsed = [row('Один ответ', null, 'a'), row('Множественный', null, 'b'), row('Текстовый', null, 'c')];
        expect(ids(sortByOperatorSeq(parsed))).toBe('a,b,c');
    });

    it('возвращает тот же массив, если сортировать нечего', () => {
        // Не копируем без нужды: импорт может быть на тысячи строк.
        const parsed = [row('Один ответ', null, 'a')];
        expect(sortByOperatorSeq(parsed)).toBe(parsed);
    });

    it('ставит строки без «№» после пронумерованных, сохраняя их взаимный порядок', () => {
        const parsed = [
            row('Один ответ', null, 'x'),
            row('Один ответ', 2, 'b'),
            row('Множественный', null, 'y'),
            row('Множественный', 1, 'a'),
        ];
        expect(ids(sortByOperatorSeq(parsed))).toBe('a,b,x,y');
    });

    it('не переставляет строки с одинаковым «№» между собой', () => {
        // Дубль «№» — ошибка оператора, но она не должна делать импорт
        // недетерминированным: при равных ключах остаётся порядок листов.
        const parsed = [row('Один ответ', 1, 'a'), row('Множественный', 1, 'b'), row('Текстовый', 1, 'c')];
        expect(ids(sortByOperatorSeq(parsed))).toBe('a,b,c');
    });

    it('не портит исходный массив', () => {
        const parsed = [row('Один ответ', 2, 'b'), row('Множественный', 1, 'a')];
        sortByOperatorSeq(parsed);
        expect(ids(parsed)).toBe('b,a');
    });
});
